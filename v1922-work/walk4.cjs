const { createRequire } = require("node:module");
const req = createRequire("D:/moodle/CityNexus/frontend/package.json");
const { chromium } = req("@playwright/test");
const fs = require("fs");
const BASE = "http://127.0.0.1:5173";
const SHOTS = "D:/moodle/_v1922_work/rescue_evidence/shots";
(async () => {
  await fetch("http://127.0.0.1:8000/api/v1/demo/reset", { method: "POST" });
  const browser = await chromium.launch({ channel: "chrome" });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await ctx.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(String(e).slice(0, 160)));
  page.on("console", (m) => { if (m.type() === "error") errors.push("C: " + m.text().slice(0, 160)); });
  await page.addInitScript(() => localStorage.setItem("citynexus.v8.journey_id", "22222222-2222-4222-8222-222222222222"));
  const out = {};
  await page.goto(BASE + "/v8/hub", { waitUntil: "networkidle", timeout: 60000 });
  await page.waitForTimeout(2500);
  out.cta_present = await page.locator('[data-testid="hub-plan-with-ai"]').count() > 0;
  out.cta_label = await page.locator('[data-testid="hub-plan-with-ai"]').innerText().catch(() => "");
  await page.screenshot({ path: SHOTS + "/40_today_cta.png" });

  await page.locator('[data-testid="hub-plan-with-ai"]').click();
  await page.waitForTimeout(800);
  out.sheet_open = await page.locator('[data-testid="plan-ai-sheet"]').count() > 0;
  await page.locator('[data-testid="plan-ai-input"]').fill("我和朋友两个人去厦门，想轻松一点，想去鼓浪屿、环岛路，想吃沙茶面和海鲜，不想太赶。");
  await page.screenshot({ path: SHOTS + "/41_plan_sheet.png" });
  await page.locator('[data-testid="plan-ai-submit"]').click();
  await page.waitForTimeout(1200);
  await page.screenshot({ path: SHOTS + "/42_plan_progress.png" });
  await page.waitForTimeout(3500);
  out.result = await page.locator('[data-testid="plan-ai-result"]').innerText().catch(() => "");
  out.reason = await page.locator('[data-testid="plan-ai-reason"]').innerText().catch(() => "");
  const bodyText = await page.locator("body").innerText();
  out.leaks_enum = /REQUEST_REPLAN|ACCEPT_REPLAN|SKIPPED_EXTERNAL_DEPENDENCY|allowed_action_classes/.test(bodyText);
  await page.screenshot({ path: SHOTS + "/43_plan_result.png" });
  out.errors = errors.slice(0, 6);
  fs.writeFileSync("D:/moodle/_v1922_work/rescue_evidence/walk4.json", JSON.stringify(out, null, 1));
  console.log(JSON.stringify(out, null, 1));
  await browser.close();
})().catch((e) => { console.error("FAIL", e); process.exit(1); });
