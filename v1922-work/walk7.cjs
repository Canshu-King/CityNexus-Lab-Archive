const { createRequire } = require("node:module");
const req = createRequire("D:/moodle/CityNexus/frontend/package.json");
const { chromium } = req("@playwright/test");
const fs = require("fs");
const BASE = "http://127.0.0.1:5173";
const SHOTS = "D:/moodle/_v1922_work/rescue_evidence/shots";
(async () => {
  await fetch("http://127.0.0.1:8000/api/v1/demo/reset", { method: "POST" });
  const browser = await chromium.launch({ channel: "chrome" });
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await ctx.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(String(e).slice(0, 170)));
  page.on("console", (m) => { if (m.type() === "error") errors.push("C: " + m.text().slice(0, 170)); });
  const api = [];
  page.on("response", (r) => { if (r.url().includes("/api/v1")) api.push(r.status() + " " + r.url().split("/api/v1")[1]); });
  await page.addInitScript(() => localStorage.setItem("citynexus.v8.journey_id", "22222222-2222-4222-8222-222222222222"));
  const out = {};
  await page.goto(BASE + "/v8/agent", { waitUntil: "networkidle", timeout: 60000 });
  await page.waitForTimeout(2200);
  await page.locator('[data-testid="v15-copilot-input"]').fill("鼓浪屿好玩吗");
  await page.locator('[data-testid="v15-copilot-submit"]').click();
  await page.waitForTimeout(4500);
  const body = await page.locator("body").innerText();
  out.len = body.length;
  out.tail = body.replace(/\n+/g, " | ").slice(-500);
  out.api = api.filter((x) => /agent|command|copilot/i.test(x)).slice(0, 6);
  await page.screenshot({ path: SHOTS + "/61_copilot_sent.png", fullPage: true });
  out.errors = errors.slice(0, 6);
  fs.writeFileSync("D:/moodle/_v1922_work/rescue_evidence/walk7.json", JSON.stringify(out, null, 1));
  console.log(JSON.stringify(out, null, 1));
  await browser.close();
})().catch((e) => { console.error("FAIL", e); process.exit(1); });
