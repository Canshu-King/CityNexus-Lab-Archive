"""Copy a working frontend node_modules into the isolated V15 workspace.

Why this exists: ``npm ci`` in the isolated workspace stalled (registry latency),
and the V15 policy allows at most two retry rounds on a dependency problem. The
Codex worktree next door already has a complete install whose ``package.json``
and ``package-lock.json`` are byte-identical to ours, so borrowing it is both
faster and risk-free.

Read-only with respect to the source: nothing is written to
``D:/moodle/CityNexus``. Stale Vite caches are skipped so the trial run starts
from a cold cache and actually exercises the bundler.
"""
from __future__ import annotations

import shutil
import sys
import time
from pathlib import Path

SRC = Path("D:/moodle/CityNexus/frontend/node_modules")
DST = Path(
    "D:/moodle/CityNexus-Tools/WorkBuddy-V15-NightLab-20260914/frontend/node_modules"
)

#: Caches from someone else's run: copying them would mask a cold-start problem.
SKIP = {".vite", ".vite-temp", ".cache"}


def main() -> int:
    if not SRC.is_dir():
        print(f"source missing: {SRC}", file=sys.stderr)
        return 1
    if not DST.parent.is_dir():
        print(f"destination parent missing: {DST.parent}", file=sys.stderr)
        return 1

    copied = skipped = 0
    started = time.time()

    def ignore(directory: str, names: list[str]) -> set[str]:
        nonlocal skipped
        ignored: set[str] = set()
        for name in names:
            if name in SKIP:
                ignored.add(name)
                skipped += 1
        return ignored

    shutil.copytree(SRC, DST, dirs_exist_ok=True, ignore=ignore, symlinks=False)
    copied = sum(1 for _ in DST.iterdir())
    print(f"top-level entries in destination: {copied}")
    print(f"skipped cache dirs: {skipped}")
    print(f"elapsed: {time.time() - started:.1f}s")
    bin_dir = DST / ".bin"
    print(f".bin entries: {len(list(bin_dir.iterdir())) if bin_dir.is_dir() else 0}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
