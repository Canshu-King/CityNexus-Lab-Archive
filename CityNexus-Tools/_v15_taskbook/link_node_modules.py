"""Point the isolated frontend's node_modules at the Codex worktree's install.

Context: ``npm ci`` stalled twice in this sandbox, and a file-by-file copy of
27,887 files stalled at 86%. Both are dependency-provisioning problems, and the
V15 policy allows at most two retries before recording and moving on.

A directory junction needs no copying and no admin rights, and it is safe here
because the V15 dev config redirects Vite's ``cacheDir`` to ``%TEMP%`` — the only
thing Vite would otherwise write inside ``node_modules``. The Codex worktree is
therefore read-only from our side; the junction only *resolves* reads into it.

``subprocess`` is used with an argument list rather than a shell string so the
spaces in ``CityNexus-Tools`` survive intact.
"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

FRONTEND = Path(
    "D:/moodle/CityNexus-Tools/WorkBuddy-V15-NightLab-20260914/frontend"
)
LINK = FRONTEND / "node_modules"
TARGET = Path("D:/moodle/CityNexus/frontend/node_modules")


def main() -> int:
    if not TARGET.is_dir():
        print(f"target missing: {TARGET}", file=sys.stderr)
        return 1

    if LINK.exists() or LINK.is_symlink():
        print(f"{LINK} already exists; nothing to do")
        return 0

    # `cmd /c mklink /J <link> <target>` — junctions do not require elevation.
    proc = subprocess.run(
        ["cmd", "/c", "mklink", "/J", str(LINK), str(TARGET)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    print(f"rc={proc.returncode}")
    if proc.stdout.strip():
        print(f"stdout: {proc.stdout.strip()}")
    if proc.stderr.strip():
        print(f"stderr: {proc.stderr.strip()}")

    if not LINK.is_dir():
        print("junction was not created", file=sys.stderr)
        return 1

    vite = LINK / ".bin" / "vite"
    lucide = LINK / "lucide-react" / "dist"
    print(f"vite present: {vite.exists()}")
    print(f"lucide-react dist present: {lucide.is_dir()}")
    print(f"entries through the link: {len(os.listdir(LINK))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
