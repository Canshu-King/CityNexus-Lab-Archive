"""Tear down the V15 Night Lab frontend dependency link, safely.

DANGER HANDLED HERE: ``node_modules`` in the isolated frontend is a **directory
junction** into ``D:/moodle/CityNexus/frontend/node_modules``. Deleting a
junction with ``rm -rf`` or ``shutil.rmtree`` makes the tooling recurse *through*
the reparse point and delete the **target's** contents — i.e. it would wipe the
Codex worktree's dependencies.

The only safe removal is ``rmdir`` on the link itself, which deletes the reparse
point and leaves the target untouched. This script does exactly that, then proves
the target is still intact before reporting success.
"""
from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

FRONTEND = Path(
    "D:/moodle/CityNexus-Tools/WorkBuddy-V15-NightLab-20260914/frontend"
)
LINK = FRONTEND / "node_modules"
TARGET = Path("D:/moodle/CityNexus/frontend/node_modules")

#: Counted BEFORE removal so we can prove nothing was lost.
EXPECTED_MIN_ENTRIES = 390


def is_reparse_point(path: Path) -> bool:
    try:
        return bool(os.lstat(path).st_file_attributes & 0x400)  # FILE_ATTRIBUTE_REPARSE_POINT
    except (OSError, AttributeError):
        return False


def main() -> int:
    before = len(os.listdir(TARGET)) if TARGET.is_dir() else -1
    print(f"target entries before: {before}")

    if not LINK.exists() and not LINK.is_symlink():
        print("link does not exist; nothing to remove")
        return 0

    if not is_reparse_point(LINK):
        print(
            "REFUSING: node_modules is a real directory, not a junction. "
            "Not touching it.",
            file=sys.stderr,
        )
        return 1

    proc = subprocess.run(
        ["cmd", "/c", "rmdir", str(LINK)],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    print(f"rmdir rc={proc.returncode}")
    if proc.stdout.strip():
        print(f"stdout: {proc.stdout.strip()}")
    if proc.stderr.strip():
        print(f"stderr: {proc.stderr.strip()}")

    after = len(os.listdir(TARGET)) if TARGET.is_dir() else -1
    print(f"target entries after:  {after}")

    if after < EXPECTED_MIN_ENTRIES:
        print(
            "TARGET DAMAGED — the Codex node_modules lost entries. Investigate now.",
            file=sys.stderr,
        )
        return 2

    print(f"link removed: {not LINK.exists()}")
    print("target intact: yes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
