"""Inspect the isolated shadow-app production bundle."""

from __future__ import annotations

import gzip
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "shadow-app" / "dist"
OUT = ROOT / "evidence" / "bundle_analysis.json"


def main() -> None:
    files = []
    total_bytes = 0
    total_gzip = 0
    for path in sorted(DIST.rglob("*")):
        if not path.is_file():
            continue
        raw = path.read_bytes()
        gz = gzip.compress(raw)
        size = len(raw)
        gzip_size = len(gz)
        total_bytes += size
        total_gzip += gzip_size
        files.append(
            {
                "file": str(path.relative_to(DIST)).replace("\\", "/"),
                "bytes": size,
                "gzip_bytes": gzip_size,
            }
        )
    payload = {
        "app": "citynexus-v19-1-shadow-app",
        "file_count": len(files),
        "total_bytes": total_bytes,
        "total_gzip_bytes": total_gzip,
        "files": files,
        "notes": [
            "No MapLibre/WebGL module is present in the shadow first-paint bundle.",
            "PWA service worker and workbox are generated by the existing vite-plugin-pwa.",
            "API responses use NetworkFirst runtime caching; stale data is still labelled OFFLINE_STALE in the UI.",
        ],
    }
    OUT.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(json.dumps({k: payload[k] for k in ("file_count", "total_bytes", "total_gzip_bytes")}, indent=2))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
